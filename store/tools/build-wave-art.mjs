// Writes public/fx-wave-art.js: a short hash of every transition sheet, used as its cache version, so new art can never
// be hidden by an old copy and nobody has to remember to bump a number. node store/tools/build-wave-art.mjs
// With --check it changes nothing and fails if the file is out of date.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
const dir = new URL("../public/img/wave/", import.meta.url), out = new URL("../public/fx-wave-art.js", import.meta.url);
const art = Object.fromEntries(readdirSync(dir).filter(f => f.endsWith(".webp")).sort().map(f => [f, createHash("sha256").update(readFileSync(new URL(f, dir))).digest("hex").slice(0, 10)]));
const body = "// GENERATED by tools/build-wave-art.mjs. Each transition sheet's content hash, used as its cache version.\nexport const ART = " + JSON.stringify(art, null, 1) + ";\n";
if (process.argv.includes("--check")) {
  const now = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (now !== body) { console.log("FAIL fx-wave-art.js is out of date: run node store/tools/build-wave-art.mjs"); process.exit(1); }
  console.log(`PASS ${Object.keys(art).length} sheets match`); process.exit(0);
}
writeFileSync(out, body); console.log(Object.keys(art).length, "sheets hashed");
