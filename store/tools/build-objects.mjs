// Builds public/fx-objects.js from the illustrator's final drawings (council/illustrator/r4-markup.txt, copied to
// tools/objects-r4.txt). Eight solid silhouettes in a 100 x 100 box. node store/tools/build-objects.mjs
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("./objects-r4.txt", import.meta.url), "utf8"), out = {};
for (const m of src.matchAll(/^### (\w+)\s*\n```html\n([\s\S]*?)\n```/gm)) out[m[1]] = m[2].trim();
const names = Object.keys(out); if (names.length !== 8) throw new Error("expected 8 drawings, found " + names.join(","));
writeFileSync(new URL("../public/fx-objects.js", import.meta.url),
  "// GENERATED by tools/build-objects.mjs from tools/objects-r4.txt. The eight section objects: solid silhouettes with\n// 3-unit knock-out cuts in a 100 x 100 box, standing on y = 94, round vessels seen from 15 degrees above.\n" +
  "export const OBJ = " + JSON.stringify(out, null, 1) + ";\n");
console.log(names.join(", "), "->", Buffer.byteLength(JSON.stringify(out)), "bytes");
