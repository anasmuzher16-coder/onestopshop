# Builds site/cp-sheet.js from the Canada Post SfSB level 4 price guide (pdftotext -table output).
# Usage: python tools/build-rates.py <t.txt>
import re, sys, json, statistics
lines = open(sys.argv[1], encoding='utf8', errors='replace').read().split('\n')
starts = [(i, 'xp' if 'Xpresspost' in l else 'exp') for i, l in enumerate(lines)
          if re.search(r'^\s*(Xpresspost|Expedited Parcel)TM prices', l)]
num = re.compile(r'^\d+\.\d+$')
tables = {'xp': {}, 'exp': {}}   # svc -> code -> {kg: price}
over30 = {'xp': {}, 'exp': {}}
bad = 0
for n, (s, svc) in enumerate(starts):
    e = s + 136
    codes = None
    for l in lines[s:e]:
        t = l.split()
        if codes is None:
            if len(t) > 4 and t[0] == 'In' and t[1] == '(kg)':
                codes = [x for x in t if re.match(r'^[A-Z]\d\d$', x)]
            continue
        if not t: continue
        if all(num.match(x) for x in t):
            if len(t) == len(codes) + 2:
                kg = float(t[0])
                for c, v in zip(codes, t[2:]): tables[svc].setdefault(c, {})[kg] = float(v)
            elif len(t) == len(codes):      # "over 30, add per 0.5" row
                for c, v in zip(codes, t): over30[svc][c] = float(v)
            else:
                bad += 1; print('UNPARSED', svc, n, len(t), len(codes), t[:4], file=sys.stderr)
kgs = [0.5, 0.75] + [x / 2 for x in range(2, 61)]
out = {}
for svc in ('exp', 'xp'):
    codes = sorted(tables[svc])
    full = [c for c in codes if all(k in tables[svc][c] for k in kgs)]
    print(svc, 'codes', len(codes), 'complete', len(full), file=sys.stderr)
    def pct(vals, p):
        v = sorted(vals); return v[min(len(v) - 1, int(len(v) * p))]
    ps = [0.0, 0.10, 0.30, 0.50, 0.90 if svc == 'exp' else 0.70, 1.0]
    zones = [[round(pct([tables[svc][c][k] for c in full], p), 2) for k in kgs] for p in ps]
    add = [round(pct([over30[svc][c] for c in full if c in over30[svc]], p), 2) for p in ps]
    out[svc] = {'zones': zones, 'over30per05': add,
                'min': [min(tables[svc][c][k] for c in full) for k in kgs],
                'max': [max(tables[svc][c][k] for c in full) for k in kgs]}
print('unparsed rows', bad, file=sys.stderr)
js = ('// GENERATED by tools/build-rates.py from Canada Post "Parcel Services Solutions for Small Business\n'
      '// price guide", savings level 4, effective June 26, 2025. Do not edit by hand.\n'
      '// zones[z][i] = price for weight row KGS[i]; z0 = cheapest rate code, z1 = p10, z2 = p30, z3 = p50,\n'
      '// z4 = p90 (Expedited) / p70 (Xpresspost), z5 = dearest rate code. min/max = sheet bounds per row.\n'
      'export const KGS = ' + json.dumps(kgs) + ';\n'
      'export const SHEET = ' + json.dumps(out) + ';\n')
open('site/cp-sheet.js', 'w', encoding='utf8', newline='\n').write(js)
